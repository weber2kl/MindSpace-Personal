async function run(action) {
  const development=process.argv.includes('--dev');
  const child=spawn(development ? process.execPath : executable,development ? ['desktop/dev.mjs','--remote-debugging-port='+port] : ['--remote-debugging-port='+port],{env:{...process.env,MINDSPACE_PERSONAL_TEST_DIR:folder},stdio:'ignore'});
  const exit=new Promise((res,rej)=>{child.once('exit',res);child.once('error',rej);});
  let browser;
  try {
    for(let i=0;i<100;i++){try{if((await fetch(`http://127.0.0.1:${port}/json/list`)).ok)break;}catch{}await delay(100);}
    browser=await chromium.connectOverCDP(`http://127.0.0.1:${port}`);
    const page=browser.contexts()[0].pages()[0];page.setDefaultTimeout(10000);
    page.on('pageerror',err=>errors.push(err.message));
    await page.locator('.app-shell').waitFor();
    await action(page);
    await page.evaluate(()=>setTimeout(()=>window.close(),10));
    assert.equal(await Promise.race([exit,delay(6000,'timeout',{ref:false})]),0);
  } finally {if(child.exitCode===null){child.kill();await exit;} await browser?.close();}
}
